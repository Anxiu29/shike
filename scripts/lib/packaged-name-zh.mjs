const pattern = new RegExp(`\\b(?:${[...map.keys()].sort((a, b) => b.length - a.length).map(escape).join('|')})\\b`, 'gi');
const genericTags = new Set(['en:foods', 'en:food', 'en:beverages', 'en:snacks', 'en:plant-based-foods', 'en:plant-based-foods-and-beverages', 'en:groceries', 'en:cereals-and-potatoes', 'en:cereals-and-their-products', 'en:meals']);

export function translatePackageName(name) {
  return simplify(name).replace(pattern, value => map.get(value.toLowerCase()))
    .replace(/\s+(?=[\u3400-\u9fff])/g, '').replace(/(?<=[\u3400-\u9fff])\s+/g, '').trim();
}

/** taxonomy仅说明商品类型，不能冒充这个商品的完整中文译名或真实配料。 */
export function localizedPackageName(product, previous, taxonomy = {}) {
  const originalName = product.product_name ?? previous;
  const sourceZh = product.product_name_zh;
  const meaningfulChinese = value => /[\u3400-\u9fff]/.test(value);
  const aliases = [];
  for (const tag of [...(product.categories_tags ?? [])].reverse()) {
    if (genericTags.has(tag)) continue;
    const zh = taxonomy[tag]?.name?.zh;
    if (zh && meaningfulChinese(zh)) aliases.push(simplify(zh));
  }
  // 人工整理的完整中文商品名优先，不能用源站泛称“纯牛奶”抹掉“特仑苏”。
  if (meaningfulChinese(previous) && !/[a-z]{3}/i.test(previous)) return { name: simplify(previous), originalName, kind: 'existing', aliases };
  if (sourceZh && meaningfulChinese(sourceZh)) {
    const brands = (Array.isArray(product.brands) ? product.brands.join(',') : product.brands ?? '').split(',');
    const brand = brands.find(value => meaningfulChinese(value))?.trim();
    const name = brand && !sourceZh.includes(brand) ? `${brand} ${sourceZh}` : sourceZh;
    return { name: simplify(name).slice(0, 200), originalName, kind: 'source', aliases };
  }
  const translated = translatePackageName(previous);
  if (translated.replace(/\s/g, '') !== simplify(previous).replace(/\s/g, '') && meaningfulChinese(translated)) return { name: translated.slice(0, 200), originalName, kind: 'translated', aliases };
  if (meaningfulChinese(previous)) return { name: simplify(previous), originalName, kind: 'existing', aliases };
  // 不将不确定的外文品牌音译成另一品牌。无可靠翻译时以真实分类作中文提示，原名同时保留。
  if (aliases.length) return { name: `${aliases[0]} · ${previous}`.slice(0, 200), originalName, kind: 'category', aliases };
  return { name: previous, originalName, kind: 'untranslated', aliases };
}
