import { test, expect, type Page } from '@playwright/test'
import { routeApkAssets } from './helpers/apk-assets'

async function addManual(page: Page, name: string, weight = '150') {
  await page.getByTestId('food-picker-manual').click()
  await page.getByTestId('manual-food-name').fill(name)
  await page.getByTestId('manual-food-weight').fill(weight)
  await page.getByTestId('confirm-manual-food').click()
}

test.beforeEach(async ({ page }) => { await routeApkAssets(page); await page.goto('/'); await expect(page.getByTestId('daily-summary')).toBeVisible() })

test('个人常用食物：首页入口、手动存库、刷新快捷添加和历史快照独立', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await expect(page.locator('.app-header .brand')).toHaveCount(0)
  await expect(page.getByTestId('header-personal-library')).toHaveCount(0)
  await page.getByTestId('open-personal-library').click()
  await expect(page.getByTestId('personal-library-empty')).toBeVisible()
  await page.getByTestId('personal-library-first-food').click()
  await page.getByTestId('manual-food-name').fill('我的日常米饭')
  await page.getByTestId('manual-food-weight').fill('150')
  await page.locator('.manual-food-nutrition summary').click()
  await page.getByTestId('manual-food-energyKcal').fill('116')
  await page.getByTestId('manual-food-proteinG').fill('2.5')
  await page.getByTestId('manual-food-fatG').fill('0.3')
  await page.getByTestId('manual-food-carbsG').fill('25.6')
  await page.getByTestId('confirm-manual-food').click()
  await expect(page.getByTestId('personal-food-library')).toBeVisible()
  await expect(page.getByTestId('meal-record')).toHaveCount(0)
  const card = page.locator('article[data-testid^="personal-food-"]').filter({ hasText: '我的日常米饭' })
  const detailButton = card.locator('[data-testid^="personal-detail-"]')
  await page.getByTestId('personal-library-search').fill('日常')
  await card.click()
  const detail = page.getByTestId('personal-food-details')
  await expect(detail).toBeVisible(); await expect(page.getByTestId('personal-detail-name')).toHaveText('我的日常米饭')
  await expect(page.getByTestId('personal-detail-total-energyKcal')).toHaveText('174 kcal')
  await expect(page.getByTestId('personal-detail-basis-energyKcal')).toHaveText('116 kcal')
  await expect(page.getByTestId('personal-detail-total-proteinG')).toHaveText('3.75 g')
  await page.keyboard.press('Escape'); await expect(detail).toHaveCount(0)
  await expect(page.getByTestId('personal-library-search')).toHaveValue('日常')
  await detailButton.focus(); await page.keyboard.press('Enter'); await expect(detail).toBeVisible()
  for (const width of [320, 390, 820]) {
    await page.setViewportSize({ width, height: 568 })
    expect(await detail.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await expect(page.getByTestId('personal-detail-add')).toBeInViewport()
    expect(await page.getByTestId('personal-detail-add').evaluate(element => { const box = element.getBoundingClientRect(); return element.contains(document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2)) })).toBe(true)
  }
  if (info.project.name === 'Chrome 手机') { await page.setViewportSize({ width: 390, height: 844 }); await detail.screenshot({ path: 'docs/screenshots/personal-food-detail-mobile.png' }) }
  await page.getByTestId('personal-detail-back').click(); await expect(detail).toHaveCount(0); await expect(detailButton).toBeFocused()
  await page.getByTestId('personal-library-search').fill('')
  await page.getByTestId('personal-food-library').getByTestId('close-sheet').click()
  await page.locator('[data-testid^="quick-food-"]').click(); await page.getByTestId('save-meal').click()
  await expect(page.getByTestId('meal-record')).toHaveCount(1)
  await page.reload()
  const quick = page.locator('[data-testid^="quick-food-"]')
  await expect(quick).toHaveCount(1)
  await expect(quick).toContainText('我的日常米饭')
  await quick.click()
  await expect(page.getByTestId('food-weight-0')).toHaveValue('150')
  await expect(page.locator('.capture-area')).toHaveCount(0)
  await page.getByTestId('food-weight-0').fill('250')
  await page.getByTestId('save-meal').click()
  await expect(page.getByTestId('meal-record')).toHaveCount(2)
  await quick.click(); await expect(page.getByTestId('food-weight-0')).toHaveValue('150')
  await page.keyboard.press('Escape')
  await page.screenshot({ path: `docs/screenshots/personal-food-home-${info.project.name.includes('手机') ? 'mobile' : info.project.name.includes('Edge') ? 'edge' : 'desktop'}.png`, fullPage: true })
  expect(errors).toEqual([])
})

test('管理常用食物：搜索、筛选、星标、删除撤销与弹窗返回', async ({ page }, info) => {
  await page.getByTestId('manual-add').click(); await addManual(page, '常用燕麦早餐', '80')
  await page.getByTestId('save-library-food-0').click(); await expect(page.getByTestId('stored-food-message-0')).toContainText('已存入食品库')
  await page.getByTestId('add-food').click(); await addManual(page, '我的豆乳', '200')
  await page.getByTestId('save-all-library-foods').click()
  await expect(page.getByTestId('stored-food-message-1')).toContainText('已存入食品库')
  await expect(page.getByTestId('save-all-library-foods')).toBeEnabled()
  await expect(page.getByTestId('save-all-library-foods')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('food-editor')).toHaveCount(0)
  await expect(page.getByTestId('meal-record')).toHaveCount(0)
  await page.getByTestId('open-personal-library').click()
  const cards = page.locator('article[data-testid^="personal-food-"]')
  await expect(cards).toHaveCount(2)
  const first = cards.filter({ hasText: '常用燕麦早餐' }), id = (await first.getAttribute('data-testid'))!.slice('personal-food-'.length)
  await page.getByTestId(`personal-favorite-${id}`).click()
  await expect(page.getByTestId('personal-food-details')).toHaveCount(0)
  await expect(page.getByTestId(`personal-favorite-${id}`)).toHaveAttribute('aria-pressed', 'true')
  await page.getByTestId('personal-filter-星标').click(); await expect(cards).toHaveCount(1)
  await page.getByTestId(`personal-favorite-${id}`).click(); await expect(page.getByTestId('personal-library-empty')).toBeVisible()
  await page.getByTestId('personal-filter-全部').click(); await expect(cards).toHaveCount(2)
  await page.getByTestId('personal-library-search').fill('不存在的点心'); await expect(page.getByTestId('personal-library-empty')).toBeVisible()
  await page.getByTestId('personal-library-search').fill('燕麦'); await expect(cards).toHaveCount(1)
  await page.getByTestId(`personal-delete-${id}`).click(); await expect(cards).toHaveCount(0)
  await page.getByTestId('personal-library-undo').click(); await expect(cards).toHaveCount(1)
  await page.getByTestId('personal-library-search').fill('')
  await page.screenshot({ path: `docs/screenshots/personal-food-library-${info.project.name.includes('手机') ? 'mobile' : info.project.name.includes('Edge') ? 'edge' : 'desktop'}.png` })
  await page.keyboard.press('Escape'); await expect(page.getByTestId('personal-food-library')).toHaveCount(0)
  await expect(page.getByTestId('open-personal-library')).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  await page.reload(); await page.getByTestId('open-personal-library').click(); await expect(cards).toHaveCount(2)
  await page.setViewportSize({ width: 320, height: 568 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await page.getByTestId(`personal-detail-${id}`).click(); await expect(page.getByTestId('personal-detail-total-energyKcal')).toHaveText('待补充')
  await page.getByTestId('personal-detail-add').click(); await expect(page.getByTestId('food-weight-0')).toHaveValue('80')
  await expect(page.getByTestId('personal-food-details')).toHaveCount(0)
  await expect(page.getByTestId('personal-food-library')).toHaveCount(0)
  await expect(page.getByTestId('save-meal')).toBeInViewport()
  await page.keyboard.press('Escape'); expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
})
